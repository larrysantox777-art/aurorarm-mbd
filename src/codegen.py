"""Gerador de codigo C a partir do MODELO (ganhos do projeto + tabela do supervisor). Nada em generated/ e digitado a mao.
Uso: python3 codegen.py  -> generated/aurora_ctrl.{h,c} (+ mutantes em tests/mutants/ para teste de sensibilidade da suite)
Trace: MOD-CTRL, MOD-SUP -> generated/aurora_ctrl.c
"""
import json, hashlib, os, re, sys
import numpy as np
sys.path.insert(0, os.path.dirname(__file__))
import refmodel as RM
from supervisor_spec import spec, STOP_CYCLES, STATES

GEN_VERSION = "codegen 1.0"
def f32(x):
    t = "%.9g" % np.float32(x)
    if not any(c in t for c in ".eEn"): t += ".0"   # garante literal de ponto flutuante em C
    return t + "f"

def c_guard(g):
    g = g.replace("STOP_CYCLES", "STOP_CYCLES")
    g = re.sub(r"\band\b", "&&", g); g = re.sub(r"\bor\b", "||", g); g = re.sub(r"\bnot\b", "!", g)
    return g

def generate(version="v1", outdir="../generated", suffix=""):
    d, _ = RM.design(); sp = spec(version)
    os.makedirs(outdir, exist_ok=True)
    manifest_src = json.dumps(dict(design={k: (float(v) if not isinstance(v, (list, str)) else v) for k, v in d.items() if k not in ("poles_ct",)},
                                    spec=sp, poles=[str(p) for p in RM.POLES_CT]), sort_keys=True, default=str)
    h = hashlib.sha256(manifest_src.encode()).hexdigest()[:16]
    name = "aurora_ctrl" + suffix
    consts = dict(K_I=d['K_I'], K_W=d['K_W'], K_TH=d['K_TH'], K_Z=d['K_Z'], K_AW=d['K_AW'], A11=d['A11'], A12=d['A12'], B1=d['B1'],
                  ILIM=d['ILIM'], VMAX=d['VMAX'], TS=d['TS'], WOVER=d['WOVER'], KE=d['KE'], RATE=d['RATE'], TWOA=d['TWOA'], DV=d['DV'])
    trace = """\
 * TRACEABILITY BLOCK (requirement -> model -> code -> test)
 *   REQ-CTRL-AA-001  zero steady-state step error   -> MOD-CTRL (integrator state z, law u=-Kx+Kz*z)   -> aurora_step()            -> TST-CTRL-001
 *   REQ-CTRL-AA-002  overshoot <= 8 %               -> MOD-CTRL (pole placement, poles in refmodel.py) -> aurora_step()            -> TST-CTRL-002
 *   REQ-CTRL-AA-003  settling time <= 300 ms        -> MOD-CTRL                                        -> aurora_step()            -> TST-CTRL-003
 *   REQ-CTRL-AA-004  |u|<=48 V, |i|<=8 A            -> MOD-CTRL (voltage clamp + predictive current clamp + anti-windup) -> aurora_step() -> TST-CTRL-004
 *   REQ-SAFE-AA-001  torque zero <= 100 ms          -> MOD-SUP (MOVING->SAFE_STOP on prox)             -> aurora_supervisor_step() -> TST-SUP-001, TST-VER-001
 *   REQ-SAFE-AA-002  no automatic restart           -> MOD-SUP (WAIT_REARM requires explicit rearm)    -> aurora_supervisor_step() -> TST-SUP-002, TST-VER-002
 *   REQ-SAFE-AA-003  resume after clear + rearm     -> MOD-SUP (WAIT_REARM->MOVING, trajectory-limited ref)  -> aurora_supervisor_step() -> TST-SUP-003, TST-VER-003
 *   REQ-SAFE-AA-004  tip speed <= 250 mm/s          -> MOD-SUP (overspeed trip) + MOD-CTRL (trajectory generator) -> aurora_step()      -> TST-SAFE-004
"""
    hdr = f"""/* AUTO-GENERATED by src/codegen.py ({GEN_VERSION}) -- DO NOT EDIT BY HAND.
 * Supervisor model version : {version}
 * Model digest (sha256/16) : {h}
 * Plant: PMDC 48 V + harmonic drive 100:1 (elbow joint of AuroraArm); sample time Ts = {d['TS']*1e3:g} ms.
 * Data type: IEEE-754 binary32 (float); compile with -ffp-contract=off -fno-fast-math for bit-exact SIL.
 *
{trace} */
#ifndef AURORA_CTRL{suffix.upper()}_H
#define AURORA_CTRL{suffix.upper()}_H
#include <stdint.h>
#ifdef __cplusplus
extern "C" {{
#endif

#define STOP_CYCLES {STOP_CYCLES}u
enum {{ SUP_MOVING = 0, SUP_SAFE_STOP = 1, SUP_WAIT_REARM = 2 }};

typedef struct {{
    float   z;          /* integral of (r_lim - theta)            */
    float   rl;         /* profile-limited reference [rad]         */
    float   v;          /* profile speed [rad/s]                   */
    uint8_t sup;        /* supervisor state                        */
    uint8_t stop_cnt;   /* cycles spent in SAFE_STOP               */
    uint8_t prev_prox;  /* used only by preliminary (buggy) model  */
    uint8_t latch;      /* used only by preliminary (buggy) model  */
}} aurora_state_t;

typedef struct {{
    float   r;          /* position reference, motor shaft [rad]   */
    float   th;         /* measured position [rad]                 */
    float   w;          /* measured speed [rad/s]                  */
    float   i;          /* measured armature current [A]           */
    uint8_t prox;       /* proximity sensor output (<500 mm)       */
    uint8_t rearm;      /* explicit operator rearm                 */
    uint8_t collab;     /* 1 = collaborative zone (trajectory limit + overspeed trip) */
}} aurora_in_t;

typedef struct {{
    float   u;          /* armature voltage command [V]            */
    float   rl;         /* limited reference [rad]                 */
    uint8_t sup;        /* supervisor state                        */
    uint8_t brake;      /* mechanical brake command                */
    uint8_t torque_en;  /* 1 while MOVING                          */
}} aurora_out_t;

void aurora_init(aurora_state_t *s);
void aurora_step(aurora_state_t *s, const aurora_in_t *in, aurora_out_t *out);

#ifdef __cplusplus
}}
#endif
#endif
"""
    # supervisor C
    sup_lines = []
    for si, sname in enumerate(STATES):
        tl = [t for t in sp['transitions'] if t[0] == sname]
        sup_lines.append(f"    case SUP_{sname}:")
        for k, (s_, d_, g, acts) in enumerate(tl):
            kw = "if" if k == 0 else "else if"
            body = f"next = SUP_{d_}; fired = 1u;" + "".join(f" s->{a.replace(' ','').replace('=','=')};" if False else " s->" + a + ";" for a in acts)
            sup_lines.append(f"        {kw} ({c_guard(g)}) {{ {body} }}")
        sup_lines.append("        break;")
    prev_upd = ""
    if sp['prev_update_in']:
        conds = " || ".join(f"cur == SUP_{s_}" for s_ in sp['prev_update_in'])
        prev_upd = f"    if ({conds}) s->prev_prox = prox;\n"
    latch_pre = "    if (rearm) s->latch = 1u;\n" if sp['uses_latch'] else ""
    latch_post = "    if (next == SUP_MOVING && cur != SUP_MOVING) s->latch = 0u;\n" if sp['uses_latch'] else ""
    # locals used by guards
    body_fn = f"""
/* ---- supervisor: generated from supervisor_spec.py ({version}) --------------------------------- */
static void aurora_supervisor_step(aurora_state_t *s, uint8_t prox, uint8_t rearm, uint8_t overspeed)
{{
    const uint8_t cur = s->sup;
    uint8_t next = cur, fired = 0u;
    const uint8_t prev_prox = s->prev_prox; const uint8_t latch_in = s->latch;
    (void)prev_prox; (void)latch_in; (void)rearm; (void)overspeed;
{latch_pre}    {{
    const uint8_t latch = s->latch; (void)latch;
    const uint8_t stop_cnt = s->stop_cnt; (void)stop_cnt;
    switch (cur) {{
{chr(10).join(sup_lines)}
    default: next = SUP_SAFE_STOP; break;   /* defensive: illegal state -> safe state */
    }}
    }}
    if (!fired && cur == SUP_SAFE_STOP && s->stop_cnt < STOP_CYCLES) s->stop_cnt++;
{prev_upd}{latch_post}    s->sup = next;
}}
"""
    # fix: guards refer to stop_cnt but actions assign s->stop_cnt: guards read the pre-action local copy (same as reference)
    c_src = f"""/* AUTO-GENERATED by src/codegen.py ({GEN_VERSION}) -- DO NOT EDIT BY HAND. Model digest {h}. See aurora_ctrl{suffix}.h for traceability. */
#include <math.h>
#include "aurora_ctrl{suffix}.h"

#define K_I   {f32(consts['K_I'])}
#define K_W   {f32(consts['K_W'])}
#define K_TH  {f32(consts['K_TH'])}
#define K_Z   {f32(consts['K_Z'])}
#define K_AW  {f32(consts['K_AW'])}
#define A11   {f32(consts['A11'])}
#define A12   {f32(consts['A12'])}
#define B1    {f32(consts['B1'])}
#define ILIM  {f32(consts['ILIM'])}
#define VMAX  {f32(consts['VMAX'])}
#define TSMP  {f32(consts['TS'])}
#define RATEV {f32(consts['RATE'])}   /* max reference speed [rad/s] (80 % of 250 mm/s limit) */
#define TWOA  {f32(consts['TWOA'])}   /* 2*A_ref */
#define DVMAX {f32(consts['DV'])}   /* A_ref*Ts */
#define WOVER {f32(consts['WOVER'])}
#define KEMF  {f32(consts['KE'])}
{body_fn}
void aurora_init(aurora_state_t *s)
{{
    s->z = 0.0f; s->rl = 0.0f; s->v = 0.0f; s->sup = SUP_MOVING; s->stop_cnt = 0u; s->prev_prox = 0u; s->latch = 0u;
}}

void aurora_step(aurora_state_t *s, const aurora_in_t *in, aurora_out_t *out)
{{
    const float th = in->th, w = in->w, i = in->i, r = in->r;
    const uint8_t over = (in->collab && (fabsf(w) > WOVER)) ? 1u : 0u;
    float u;
    aurora_supervisor_step(s, in->prox, in->rearm, over);
    const uint8_t brake = (s->sup != SUP_MOVING && s->stop_cnt >= STOP_CYCLES) ? 1u : 0u;
    if (s->sup == SUP_MOVING) {{
        if (in->collab) {{
            const float e = r - s->rl;
            float vd = sqrtf(TWOA * fabsf(e));
            if (vd > RATEV) vd = RATEV;
            if (e < 0.0f) vd = -vd;
            float dv = vd - s->v;
            if (dv > DVMAX) dv = DVMAX;
            if (dv < -DVMAX) dv = -DVMAX;
            s->v = s->v + dv;
            float rn = s->rl + s->v * TSMP;
            if ((r - rn) * e <= 0.0f) {{ rn = r; s->v = 0.0f; }}
            s->rl = rn;
        }} else {{
            s->rl = r; s->v = 0.0f;
        }}
        const float uu = ((-K_I * i - K_W * w) - K_TH * th) + K_Z * s->z;
        float us = uu;
        if (us > VMAX) us = VMAX;
        if (us < -VMAX) us = -VMAX;
        const float lo = (-ILIM - A11 * i - A12 * w) / B1;
        const float hi = ( ILIM - A11 * i - A12 * w) / B1;
        if (us > hi) us = hi;
        if (us < lo) us = lo;
        s->z = s->z + TSMP * (s->rl - th) + K_AW * (us - uu);   /* back-calculation anti-windup */
        u = us;
    }} else {{
        u = KEMF * w;                 /* safe stop: cancel back-EMF so that i decays with L/R */
        if (u > VMAX) u = VMAX;
        if (u < -VMAX) u = -VMAX;
        if (brake) u = 0.0f;
        s->rl = th; s->v = 0.0f;       /* hold reference at current position; resume heads to the original target */
    }}
    out->u = u; out->rl = s->rl; out->sup = s->sup; out->brake = brake; out->torque_en = (s->sup == SUP_MOVING) ? 1u : 0u;
}}
"""
    open(os.path.join(outdir, name + ".h"), "w").write(hdr)
    open(os.path.join(outdir, name + ".c"), "w").write(c_src)
    return dict(files=[name + ".h", name + ".c"], digest=h, version=version)

if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    out = {}
    out['v1'] = generate("v1", os.path.join(here, "../generated"))
    out['v0_edge'] = generate("v0_edge", os.path.join(here, "../tests/mutants"), "_v0_edge")
    out['v0_stale_rearm'] = generate("v0_stale_rearm", os.path.join(here, "../tests/mutants"), "_v0_stale_rearm")
    json.dump(out, open(os.path.join(here, "../generated/manifest.json"), "w"), indent=1)
    print(json.dumps(out, indent=1))
